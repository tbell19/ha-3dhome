/* Saving: the edited layout goes to the card's layout store. That is the dashboard the card sits on, unless whoever
 * made the card (the 3D Home panel) handed it another store.
 */
import type { CardConfig, Layout, LayoutStore } from "../types";
import type { EditorHost } from "../editor-contract";
import type { Editor } from "./editor";
import { STRATEGY_TYPES, LAYOUT_KEYS, findCard, strategyCard, stableJSON } from "./shared";

/** the layout part of a config; a key that is missing stays in as undefined, so saving removes it */
export function layoutOf(config: CardConfig): Layout {
  const out: Record<string, unknown> = {};
  for (const k of LAYOUT_KEYS) out[k] = config[k];
  return out as Layout;
}

/** Saves into the Lovelace dashboard the card is on: into the strategy config of a 3D Home dashboard, or else into
 * this card's entry among the dashboard's views (matched by type and card_id). */
export function dashboardStore(card: EditorHost): LayoutStore {
  return {
    savedMessage: "Saved to the dashboard",
    async save(layout, config) {
      const seg = config.dashboard || decodeURIComponent(location.pathname.split("/")[1] || "lovelace");
      const url_path = seg === "lovelace" ? null : seg;
      const lc = await card._hass.callWS({ type: "lovelace/config", url_path, force: true });
      if (lc.strategy && STRATEGY_TYPES.includes(lc.strategy.type)) {
        // a dashboard generated by the strategy (current or old name): the layout lives in the strategy config
        Object.assign(lc.strategy, layout);
        await card._hass.callWS({ type: "lovelace/config/save", url_path, config: lc });
        return strategyCard(lc.strategy); // what the strategy will hand the card back
      }
      const out = { ...config, ...layout };
      const mine = findCard(lc.views, (c, replace) => {
        if (config.card_id && c.card_id !== config.card_id) return false;
        replace(out);
        return true;
      });
      if (!mine) throw new Error("couldn't find this card in the dashboard config");
      await card._hass.callWS({ type: "lovelace/config/save", url_path, config: lc });
      return out;
    },
  };
}

export class EditorSave {
  async _save(this: Editor) {
    const card = this.card,
      btn = card._ed.querySelector<HTMLButtonElement>('[data-a="save"]');
    if (card._offSince)
      return card._toast("Not connected to Home Assistant. Your changes are kept: save again once it's back", 5000);
    btn.disabled = true;
    btn.textContent = "Saving…";
    try {
      const store = card._layoutStore || dashboardStore(card);
      const config = await store.save(layoutOf(card._work), card._config);
      card._edit.dirty = false;
      // remember the config about to come back (from the dashboard or the panel), so it isn't seen as a change
      card._config = config;
      card._cfgJSON = stableJSON(config);
      card._toast(store.savedMessage);
      this._exitEdit(false);
    } catch (e: any) {
      console.error(e);
      card._toast("Save failed: " + (e.message || e.code || e), 5000);
      btn.disabled = false;
      this._syncBar();
    }
  }
}
